import AppKit

struct ClipEntry: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String
    var copiedAt: Date
    var app: String?
}

struct Snippet: Codable, Identifiable, Equatable {
    var id = UUID()
    var title: String
    var text: String
}

/// Text clipboard history plus saved snippets. Images are the Shelf's job; anything a
/// password manager marks as concealed or transient is never recorded.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var history: [ClipEntry]
    @Published private(set) var snippets: [Snippet]

    private let historyFile = JSONFile<[ClipEntry]>("clipboard.json")
    private let snippetsFile = JSONFile<[Snippet]>("snippets.json")
    private let limit = 40
    private let maxLength = 20_000
    private var lastChange = NSPasteboard.general.changeCount
    private var ownChange = -1
    private var timer: Timer?

    static let skippedTypes: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ].map { NSPasteboard.PasteboardType($0) }

    init() {
        history = historyFile.load() ?? []
        snippets = snippetsFile.load() ?? []
    }

    func start() {
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: History

    func copy(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        ownChange = board.changeCount
        record(text, app: nil)
    }

    func remove(_ entry: ClipEntry) {
        history.removeAll { $0.id == entry.id }
        historyFile.save(history)
    }

    func clearHistory() {
        history.removeAll()
        historyFile.save(history)
    }

    // MARK: Snippets

    func saveSnippet(id: UUID? = nil, title: String, text: String) {
        let body = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !body.isEmpty else { return }
        let name = title.trimmingCharacters(in: .whitespacesAndNewlines)
        if let id, let index = snippets.firstIndex(where: { $0.id == id }) {
            snippets[index].title = name
            snippets[index].text = body
        } else {
            snippets.append(Snippet(title: name, text: body))
        }
        snippetsFile.save(snippets)
    }

    func deleteSnippet(_ snippet: Snippet) {
        snippets.removeAll { $0.id == snippet.id }
        snippetsFile.save(snippets)
    }

    // MARK: Watching

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard board.changeCount != ownChange else { return }
        let types = board.types ?? []
        guard !types.contains(where: Self.skippedTypes.contains), !types.contains(.fileURL),
              let text = board.string(forType: .string) else { return }
        record(text, app: NSWorkspace.shared.frontmostApplication?.localizedName)
    }

    private func record(_ text: String, app: String?) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= maxLength else { return }
        let previous = history.first { $0.text == text }
        history.removeAll { $0.text == text }
        history.insert(ClipEntry(text: text, copiedAt: .now, app: app ?? previous?.app), at: 0)
        if history.count > limit { history = Array(history.prefix(limit)) }
        historyFile.save(history)
    }
}
